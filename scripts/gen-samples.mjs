// Generator for built-in sample specimens. Encodes models using compiled format modules,
// verifies round-trip, writes files to public/samples/, and updates src/samples/data.ts.

import fs from 'fs';
import path from 'path';
import assert from 'assert';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Import compiled format modules and core utilities
const { macpaint } = await import('../mcp/dist/formats/macpaint/index.js');
const { pcx } = await import('../mcp/dist/formats/pcx/index.js');
const { ilbm } = await import('../mcp/dist/formats/ilbm/index.js');
const { wk1 } = await import('../mcp/dist/formats/wk1/index.js');
const { dbf } = await import('../mcp/dist/formats/dbf/index.js');
const { wordstar } = await import('../mcp/dist/formats/wordstar/index.js');
const { exhume } = await import('../mcp/dist/core/registry.js');
const { coverage } = await import('../mcp/dist/core/annotations.js');

// Import sample data models
const { ghostMac, pumpkinPcx, moonIff } = await import('./samples/images.mjs');
const { budgetWk1, residentDbf, letterWs } = await import('./samples/data.mjs');

const SAMPLES_DIR = path.join(__dirname, '../public/samples');
const DATA_TS = path.join(__dirname, '../src/samples/data.ts');

// Ensure samples directory exists
if (!fs.existsSync(SAMPLES_DIR)) {
  fs.mkdirSync(SAMPLES_DIR, { recursive: true });
}

/**
 * Encode a sample, verify it round-trips correctly, return bytes and metadata.
 */
function encodeSample(model, module, filename, title, blurb) {
  const bytes = module.encode(model);
  
  // Verify round-trip
  const { module: detectedModule, specimen } = exhume(bytes, filename);
  assert.strictEqual(detectedModule.id, module.id, `Format detection failed for ${filename}`);
  assert.strictEqual(specimen.payload.kind, model.kind, `Payload kind mismatch for ${filename}`);
  assert.deepStrictEqual(specimen.payload, model, `Round-trip payload mismatch for ${filename}`);
  assert.strictEqual(specimen.warnings.length, 0, `Warnings found for ${filename}: ${specimen.warnings.map(w => w.message).join(', ')}`);
  
  // Verify annotation coverage (top-level annotations cover all bytes exactly once)
  const cov = coverage(specimen.annotations, bytes.length);
  assert.strictEqual(cov.exact, true, `Annotations don't cover bytes exactly for ${filename}`);
  
  return { bytes, formatId: module.id, title, blurb, file: filename };
}

/**
 * Main generator flow
 */
const samples = [
  encodeSample(ghostMac(), macpaint, 'GHOST.MAC', 'A ghost, drawn in 1-bit', 'Night scene with moon, tombstones, and a ghost.'),
  encodeSample(pumpkinPcx(), pcx, 'PUMPKIN.PCX', 'Jack-o\'-lantern, 8-bit', 'Glowing pumpkin on a gradient backdrop.'),
  encodeSample(moonIff(), ilbm, 'MOON.IFF', 'Moon and tree, 5-plane', 'Amiga sunset with moon and silhouette.'),
  encodeSample(budgetWk1(), wk1, 'BUDGET87.WK1', 'Household budget 1987', 'Lotus 1-2-3 spreadsheet with formulas.'),
  encodeSample(residentDbf(), dbf, 'RESIDENT.DBF', 'Graveyard register', 'dBASE table of dead technologies.'),
  encodeSample(letterWs(), wordstar, 'LETTER.WS', 'Letter from 1986', 'WordStar letter with formatting and page break.'),
];

// Write sample files
console.log(`Writing ${samples.length} sample files to ${SAMPLES_DIR}/`);
for (const sample of samples) {
  const filePath = path.join(SAMPLES_DIR, sample.file);
  fs.writeFileSync(filePath, sample.bytes);
  console.log(`  ${sample.file} (${sample.bytes.length} bytes)`);
}

// Write index.json
const index = samples.map(s => ({
  file: s.file,
  formatId: s.formatId,
  title: s.title,
  blurb: s.blurb,
}));
fs.writeFileSync(path.join(SAMPLES_DIR, 'index.json'), JSON.stringify(index, null, 2));
console.log(`  index.json`);

// Generate src/samples/data.ts
const header = `// GENERATED by \`npm run samples\` (scripts/gen-samples.mjs). Do not edit by hand.
// Built-in sample specimens, embedded so the app needs no network to show them.
export interface SampleSpecimen {
  file: string;
  formatId: string;
  title: string;
  blurb: string;
  base64: string;
}

`;

const entries = samples.map(s => {
  const base64 = Buffer.from(s.bytes).toString('base64');
  return `  {
    file: ${JSON.stringify(s.file)},
    formatId: ${JSON.stringify(s.formatId)},
    title: ${JSON.stringify(s.title)},
    blurb: ${JSON.stringify(s.blurb)},
    base64: ${JSON.stringify(base64)},
  }`;
}).join(',\n');

const dataTs = `${header}export const samples: SampleSpecimen[] = [
${entries}
];
`;

fs.writeFileSync(DATA_TS, dataTs);
console.log(`\nGenerated ${DATA_TS}`);

console.log(`\nAll samples generated successfully!`);
