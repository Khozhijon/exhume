// The upper halves below were generated from the Unicode Consortium mappings as shipped in Python's
// codecs (cp437, cp850, cp1252, mac_roman) so they are data, not recollection. Undefined bytes map to
// U+FFFD. Bytes 0x00-0x7F are ASCII in all four tables.

function upper(codes: readonly number[]): readonly string[] {
  return codes.map((c) => String.fromCharCode(c));
}

