export type CodePage = (byte: number) => string;

function lookup(table: readonly string[]): CodePage {
  return (byte: number): string => {
    const b = byte & 0xff;
    return b < 0x80 ? String.fromCharCode(b) : (table[b - 0x80] ?? '\ufffd');
  };
}

/** IBM PC / MS-DOS US (dBASE default). */
export const cp437: CodePage = lookup(CP437);
/** MS-DOS Latin-1 (Western Europe). */
export const cp850: CodePage = lookup(CP850);
/** Windows Latin-1. */
export const cp1252: CodePage = lookup(CP1252);
/** Classic Mac OS Roman. */
export const macRoman: CodePage = lookup(MAC_ROMAN);
/** ISO 8859-1: every byte is the code point of the same number (used as the LICS approximation). */
export const latin1: CodePage = (byte: number): string => String.fromCharCode(byte & 0xff);

/** Decode a byte array to a JS string with the given code page. */
export function decodeBytes(bytes: Uint8Array, decode: CodePage): string {
  let out = '';
  for (let i = 0; i < bytes.length; i++) out += decode(bytes[i]!);
  return out;
}

const reverseCache = new Map<CodePage, Map<string, number>>();

/**
 * Encode a string with the given code page (the inverse of decodeBytes, used by encoders).
 * Characters the code page cannot represent become `?` (0x3F).
 */
export function encodeString(text: string, decode: CodePage): Uint8Array {
  let reverse = reverseCache.get(decode);
  if (!reverse) {
    reverse = new Map<string, number>();
    for (let b = 255; b >= 0; b--) reverse.set(decode(b), b);
    reverseCache.set(decode, reverse);
  }
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) out[i] = reverse.get(text[i]!) ?? 0x3f;
  return out;
}

/** True when every character of `text` survives encodeString/decodeBytes unchanged. */
export function isEncodable(text: string, decode: CodePage): boolean {
  return decodeBytes(encodeString(text, decode), decode) === text;
}
